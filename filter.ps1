if (!(Test-Path $inputFile)) {
    Write-Host "Input file not found"
    exit 1
}

$result = @()

Get-Content $inputFile | ForEach-Object {

    if ($_ -match "^vless://") {

        if ($_ -match "@([^:]+):(\d+)") {

            $ip   = $matches[1]
            $port = $matches[2]
            $ipPort = "$ip`:$port"

            if ($allowed -contains $ipPort) {
                $result += $_
            }
        }
    }
}

$result | Set-Content $outputFile -Encoding UTF8

Write-Host "Filtered servers: $($result.Count)"
